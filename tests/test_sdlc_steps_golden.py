"""S2: the ordered steps of the sdlc stage job are pinned byte for byte in tests/golden/sdlc-steps.txt.

The golden file is generated by `render()` below (python tests/test_sdlc_steps_golden.py), never written by hand.
The test re-renders the steps from the workflow YAML and compares. A step moved between files keeps its place in
the list only if the split is faithful. Parses YAML only; no network, no git.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "tests" / "golden" / "sdlc-steps.txt"
WORKFLOWS = [ROOT / ".github" / "workflows" / "sdlc.yml"]


def steps_in_order():
    """Every step of every job that has steps, in file order, across the sdlc workflow files."""
    out = []
    for path in WORKFLOWS:
        if not path.exists():
            continue
        for job in yaml.safe_load(path.read_text())["jobs"].values():
            out.extend(job.get("steps", []))
    return out


def render():
    lines = []
    for s in steps_in_order():
        record = {
            "name": s.get("name", s.get("uses", "")),
            "uses": s.get("uses"),
            "run": s.get("run"),
            "if": s.get("if"),
            "env": s.get("env"),
        }
        lines.append(json.dumps(record, sort_keys=True, ensure_ascii=False))
    return "\n".join(lines) + "\n"


def test_the_stage_steps_match_the_golden_list_byte_for_byte():
    assert GOLDEN.read_text(encoding="utf-8") == render()


if __name__ == "__main__":
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(render(), encoding="utf-8")
    print(f"wrote {GOLDEN} ({len(steps_in_order())} steps)")
    sys.exit(0)
