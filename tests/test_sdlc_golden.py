"""ADR-065 (S1 D): the sdlc engine's rendered text, compared byte for byte with tests/golden/.

The golden files are the stage prompt for every stage (the common rules and the stage's task; support-l1 is one of them)
and the budget gate's blocked comment, rendered with career-ai's .github/sdlc-config.json. They are generated by the
engine, never written by hand. To regenerate after a deliberate wording change:

    PYTHONPATH=src python tests/test_sdlc_golden.py

and review the diff. The test itself only compares; it never writes.
"""
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest

import sdlc_engine as sdlc
from sdlc_engine import budget, config

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / ".github" / "sdlc-config.json"
GOLDEN = ROOT / "tests" / "golden"
ENGINE_NAMES = ("AGENT_BRANCH_PREFIX", "TRUSTED", "WORK", "LABEL_TO_STAGE", "REQUESTABLE_LABELS", "STAGES", "PROTECTED",
                "MAX_FILES", "MAX_ADDED_BYTES", "_CREDENTIAL")
BUDGET_NAMES = ("MIN_RUN_SECONDS", "DEFAULT_CAP_24H", "DEFAULT_CAP_7D")
NOW = datetime(2026, 11, 20, 12, 0, tzinfo=timezone.utc)


def apply_career_ai_config():
    cfg = config.load(CONFIG)
    sdlc.configure(cfg)
    budget.configure(cfg)


@pytest.fixture
def configured(monkeypatch):
    """The engine with career-ai's config applied; every engine value is restored after the test."""
    for name in ENGINE_NAMES:
        monkeypatch.setattr(sdlc, name, getattr(sdlc, name))
    for name in BUDGET_NAMES:
        monkeypatch.setattr(budget, name, getattr(budget, name))
    apply_career_ai_config()


def _stage_decisions():
    """One real decision per stage, from a labelled issue, so the prompt carries the same fields a run would."""
    labels = sdlc.LABEL_TO_STAGE
    out = {}
    for label, stage in sorted(labels.items(), key=lambda kv: kv[1]):
        event = {"action": "labeled", "label": {"name": label}, "sender": {"type": "User", "login": "owner"},
                 "issue": {"number": 7, "title": "Add a thing", "state": "open", "labels": [],
                           "author_association": "OWNER", "user": {"login": "owner"}}}
        decision = sdlc.decide(event, [])
        assert decision["run"] and decision["stage"] == stage, label
        out[stage] = decision
    return out


def budget_comment():
    """The comment the budget gate writes when blocked: one run of 61 minutes in the last 24 hours, cap 60."""
    run = {"id": 900, "status": "completed", "conclusion": "success",
           "run_started_at": "2026-11-20T00:00:00Z", "updated_at": "2026-11-20T01:01:00Z"}
    result = budget.evaluate([run], "1", NOW, 60, 240)
    assert not result["allowed"]
    return budget.render_comment(result) + "\n"


def render_all():
    """{file name: exact text} for every golden file, as the engine renders it now."""
    out = {f"prompt-{stage}.md": sdlc.render_prompt(d) for stage, d in _stage_decisions().items()}
    out["budget-blocked.txt"] = budget_comment()
    return out


def write_golden():
    apply_career_ai_config()
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for name, text in render_all().items():
        (GOLDEN / name).write_bytes(text.encode("utf-8"))


def test_the_golden_files_are_exactly_the_engine_output(configured):
    expected = render_all()
    present = {p.name for p in GOLDEN.iterdir() if p.is_file()}
    assert present == set(expected), "golden files missing or stray: " + ", ".join(sorted(present ^ set(expected)))
    for name, text in expected.items():
        assert (GOLDEN / name).read_bytes() == text.encode("utf-8"), f"tests/golden/{name} differs from the engine"


def test_there_is_a_golden_prompt_for_every_stage_including_support_l1(configured):
    assert set(_stage_decisions()) == set(sdlc.STAGES)
    assert (GOLDEN / "prompt-support-l1.md").is_file()


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    write_golden()
    print(f"wrote {len(render_all())} golden files to {GOLDEN}")
